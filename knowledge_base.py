def get_all():
    """返回全部知识库条目（副本）。"""
    return [dict(item) for item in KNOWLEDGE_BASE]


def search(text, top_n=3):
    """
    在故障描述 text 中与知识库关键词做命中打分，
    返回匹配度最高的 top_n 条，每条附带 score 与命中关键词。
    """
    if not text:
        return []
    text_lower = text.lower()
    scored = []
    for item in KNOWLEDGE_BASE:
        hits = []
        score = 0
        for kw in item["keywords"]:
            kw_lower = kw.lower()
            if kw_lower and kw_lower in text_lower:
                # 短关键词权重略低，避免单字误命中
                w = 2 if len(kw) <= 2 else 3
                score += w
                hits.append(kw)
        if score > 0:
            scored.append({
                "id": item["id"],
                "name": item["name"],
                "category": item["category"],
                "score": score,
                "hits": hits,
                "suggestions": item["suggestions"],
                "symptoms": item["symptoms"],
            })
    scored.sort(key=lambda x: x["score"], reverse=True)
    return scored[:top_n]


